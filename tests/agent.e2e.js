import { test, expect } from '@playwright/test';
test('AAPL → scenario → invalidazione → agente → cambio contesto', async ({ page }) => {
    await page.goto('/');
    await expect(page.getByRole('heading', { name: 'AAPL' })).toBeVisible();
    await expect(page.getByText('Contesto: AAPL · 1D')).toBeVisible();
    await page.getByRole('button', { name: /Company/ }).click();
    await expect(page.getByRole('heading', { name: 'Apple Inc.', exact: true })).toBeVisible();
    await expect(page.getByText('IN PAROLE SEMPLICI')).toBeVisible();
    await expect(page.getByText(/Yahoo Finance · quoteSummary/)).toBeVisible();
    await page.getByRole('button', { name: /Grafico/ }).click();
    await page.getByRole('checkbox', { name: 'RSI', exact: true }).check();
    await page.getByRole('checkbox', { name: 'MACD', exact: true }).check();
    await expect(page.locator('.indicator-pane').filter({ hasText: 'RSI (14)' })).toBeVisible();
    await expect(page.locator('.indicator-pane').filter({ hasText: 'MACD (12,26,9)' })).toBeVisible();
    await expect(page.getByText('SCENARIO TECNICO')).toBeVisible();
    const invalidation = page.getByRole('button', { name: 'Evidenzia invalidazione' }).first();
    await expect(invalidation).toBeVisible();
    await invalidation.click();
    await expect(page.getByText('Livello validato').first()).toBeVisible();
    await page.getByPlaceholder('Chiedi un’analisi o modifica il grafico…').fill('Mostra RSI e MACD');
    await page.getByLabel('Invia').click();
    await expect(page.locator('.ai-annotations>span').filter({ hasText: 'RSI' }).first()).toBeVisible();
    await expect(page.locator('.ai-annotations>span').filter({ hasText: 'MACD' }).first()).toBeVisible();
    await page.getByPlaceholder('Chiedi un’analisi o modifica il grafico…').fill('Cosa invalida l’analisi?');
    await page.getByLabel('Invia').click();
    await expect(page.locator('.chat-messages').getByText(/Invalidazioni calcolate/)).toBeVisible();
    await page.getByRole('button', { name: '1W' }).click();
    await expect(page.getByText('Contesto: AAPL · 1W')).toBeVisible();
    await expect(page.locator('.technical-scenario').getByText('1W').first()).toBeVisible();
    await expect(page.getByText('Livello validato')).toHaveCount(0);
    const search = page.getByRole('combobox');
    await search.fill('MSFT');
    await page.getByRole('option').filter({ hasText: 'MSFT' }).first().click();
    await expect(page.getByRole('heading', { name: 'MSFT' })).toBeVisible();
    await expect(page.getByText('Contesto: MSFT · 1W')).toBeVisible();
    await expect(page.getByText('Livello validato')).toHaveCount(0);
});
